import {
  copyFile,
  mkdir,
  readFile,
  readdir,
  rm,
  writeFile,
} from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const posts = path.join(root, 'apps/api/mock-data/posts');
const collection = { information: [], scholarships: [], events: [] };
const kinds = {
  information: 'information',
  scholarships: 'scholarship',
  events: 'event',
};
const ids = new Set();

// These directories contain generated copies only; recreate them so moved or
// unpublished posts do not leave attachments at their previous public URLs.
for (const target of [
  'apps/web/public/media/mock',
  'apps/api/public/media/mock',
]) {
  await rm(path.join(root, target), { recursive: true, force: true });
}

// Only publish explicitly selected fields and image files. The Facebook HTML
// stays in tmp/ and is never copied into the public build.
for (const kind of Object.keys(collection)) {
  const directory = path.join(posts, kind);
  const entries = await readdir(directory, { withFileTypes: true }).catch(
    (error) => {
      if (error.code === 'ENOENT') return [];
      throw error;
    },
  );
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory()) continue;
    const folder = path.join(directory, entry.name);
    const metadata = JSON.parse(
      await readFile(path.join(folder, 'metadata.json'), 'utf8'),
    );
    if (
      metadata.kind !== kinds[kind] ||
      metadata.slug !== entry.name ||
      !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(metadata.slug) ||
      !metadata.id ||
      !metadata.title ||
      !metadata.summary ||
      !metadata.category ||
      ids.has(metadata.id) ||
      (metadata.publishedAt &&
        !Number.isFinite(Date.parse(metadata.publishedAt)))
    ) {
      throw new Error(`Invalid or duplicate mock metadata: ${folder}`);
    }
    ids.add(metadata.id);
    if (metadata.publicationStatus !== 'published') continue;
    if (metadata.contentFile !== 'content.md') {
      throw new Error(`Expected content.md: ${folder}`);
    }
    const content = await readFile(path.join(folder, 'content.md'), 'utf8');
    const item = {
      id: metadata.id,
      slug: metadata.slug,
      kind: metadata.kind,
      title: metadata.title,
      originalTitle: metadata.originalTitle,
      eventName: metadata.eventName,
      summary: metadata.summary,
      category: metadata.category,
      publishedAt: metadata.publishedAt,
      publishedAtPrecision: metadata.publishedAtPrecision,
      content: content.trimEnd(),
      authorName: metadata.author?.name,
      authorUrl: metadata.author?.url,
      sourceUrl: metadata.source?.url,
      tags: metadata.tags,
      images: [],
    };
    for (const image of metadata.images ?? []) {
      if (!/^images\/[a-zA-Z0-9_-]+\.(jpg|jpeg|png|webp)$/.test(image.path)) {
        throw new Error(`Invalid attachment image path: ${folder}`);
      }
      const mediaPath = `${kind}/${metadata.slug}/${path.basename(image.path)}`;
      for (const target of ['apps/web/public', 'apps/api/public']) {
        const destination = path.join(root, target, 'media/mock', mediaPath);
        await mkdir(path.dirname(destination), { recursive: true });
        await copyFile(path.join(folder, image.path), destination);
      }
      item.images.push({
        url: `/media/mock/${mediaPath}`,
        alt: image.alt,
        width: image.width,
        height: image.height,
      });
    }
    if (kind === 'scholarships') {
      for (const field of [
        'provider',
        'eligibility',
        'opensAt',
        'closesAt',
        'status',
      ])
        item[field] = metadata[field];
    }
    if (kind === 'events') {
      for (const field of [
        'startsAt',
        'startsOn',
        'endsOn',
        'location',
        'status',
      ])
        item[field] = metadata[field];
    }
    collection[kind].push(item);
  }
  collection[kind].sort(
    (a, b) =>
      Date.parse(b.publishedAt ?? '1970-01-01') -
      Date.parse(a.publishedAt ?? '1970-01-01'),
  );
}

const output = path.join(root, 'packages/shared/src/generated/mock-content.ts');
await mkdir(path.dirname(output), { recursive: true });
await writeFile(
  output,
  `// Generated by scripts/prepare-mock-content.mjs. Edit apps/api/mock-data instead.\nimport type { ContentMap } from '../index';\n\nexport const mockContent = ${JSON.stringify(collection, null, 2)} satisfies { [K in keyof ContentMap]: ContentMap[K][] };\n`,
);
console.log(
  `Prepared ${Object.values(collection).flat().length} mock post(s) and local media.`,
);
